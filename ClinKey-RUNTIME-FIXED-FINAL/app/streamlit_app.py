def confidence_color(conf: str) -> str:
    return {
        "HIGH": "#0E7A52" if not SS.dark_mode else "#4BD79A",
        "MEDIUM": "#B05A00" if not SS.dark_mode else "#F0A64B",
        "LOW": "#B05A00" if not SS.dark_mode else "#F0A64B",
    }.get(conf, "#8A99A8")


def chip(text: str, color: str) -> str:
    return (
        f'<span class="ck-chip" style="color:{color};border-color:{color}80;">'
        f"{html.escape(text)}</span>"
    )


def _messages_from_session(session) -> list[dict]:
    msgs = []
    for m in session.messages:
        if m.role == "user":
            msgs.append({
                "role": "user",
                "original_text": m.original_text,
                "detected_language": m.detected_language,
                "canonical_english": m.canonical_english_text,
                "language_name": m.detected_language,
            })
        else:
            msgs.append({
                "role": "assistant",
                "localized_answer": m.localized_answer,
                "english_answer": m.english_answer,
                "target_language": m.target_language,
                "citations": m.citations,
                "confidence": m.confidence,
                "safety": m.safety_classification,
                "evidence": [],
                "canonical_english": m.canonical_english_text,
                "detected_language": m.detected_language,
                "language_name": m.target_language,
                "providers": {},
                "elapsed_ms": 0,
                "topics": m.topics,
                "intents": m.intents,
            })
    return msgs


