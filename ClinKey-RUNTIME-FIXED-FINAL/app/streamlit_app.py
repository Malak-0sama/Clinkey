def _persist(m: dict, role: str) -> None:
    """Mirror a rendered message into the (per-user) history repository."""
    msg = Message(role=role)
    if role == "user":
        msg.original_text = m["original_text"]
        msg.detected_language = m.get("detected_language", "")
        msg.canonical_english_text = m.get("canonical_english", "")
    else:
        msg.original_text = m.get("canonical_english", "")
        msg.detected_language = m.get("detected_language", "")
        msg.canonical_english_text = m.get("canonical_english", "")
        msg.english_answer = m.get("english_answer", "")
        msg.localized_answer = m.get("localized_answer", "")
        msg.target_language = m.get("target_language", "")
        msg.citations = m.get("citations", [])
        msg.confidence = m.get("confidence", "")
        msg.safety_classification = m.get("safety", "")
        msg.topics = m.get("topics", [])
        msg.intents = m.get("intents", [])
    repo.add_message(SS.session_id, msg)


def _previous_user_query() -> str:
    """Return the previous user message (for follow-up context resolution)."""
    for m in reversed(SS.messages):
        if m["role"] == "user":
            return m["original_text"]
    return ""


def _process_question(question: str) -> None:
    """Run a question through the pipeline, render the answer, and persist."""
    context = _previous_user_query()
    SS.messages.append({"role": "user", "original_text": question})
    _persist(SS.messages[-1], "user")

    with st.chat_message("assistant", avatar=LOGO_IMAGE if LOGO_IMAGE is not None else None):
        with st.spinner("Retrieving evidence and grounding the answer…"):
            result = pipeline.process(question, session_id=SS.session_id, context_query=context)

        st.markdown(result.localized_answer or result.english_answer or "*No answer produced.*")

        badges = []
        if result.confidence:
            badges.append(chip(f"Confidence: {result.confidence}", confidence_color(result.confidence)))
        if result.safety_classification and result.safety_classification != "ALLOWED":
            badges.append(chip(f"Safety: {result.safety_classification}", "#B05A00"))
        if result.detected_language != "en":
            badges.append(chip(f"Language: {result.detected_language}", "#0060A0"))
        if result.error:
            badges.append(chip("Partial error", "#B3261E"))
        if badges:
            st.markdown("".join(badges), unsafe_allow_html=True)

        if result.citations:
            with st.expander(f"References ({len(result.citations)})"):
                _render_citations(result.citations)

        if result.evidence:
            with st.expander(f"Evidence panel ({len(result.evidence)} chunks)"):
                _render_evidence(result.evidence)

        st.markdown(
            f"<div class='ck-disclaimer'>{html.escape(settings.app_disclaimer)}</div>",
            unsafe_allow_html=True,
        )

    SS.messages.append({
        "role": "assistant",
        "localized_answer": result.localized_answer or result.english_answer,
        "english_answer": result.english_answer,
        "target_language": result.target_language,
        "citations": result.citations,
        "confidence": result.confidence,
        "safety": result.safety_classification,
        "evidence": result.evidence,
        "canonical_english": result.canonical_english_query,
        "detected_language": result.detected_language,
        "language_name": result.language_name,
        "providers": result.providers,
        "elapsed_ms": result.elapsed_ms,
        "topics": result.topics,
        "intents": result.intents,
    })
    _persist(SS.messages[-1], "assistant")
    # Update the chat title to reflect the whole conversation's main idea
    # (not just the first question).
    repo.rename_session(SS.session_id, _main_idea_title(SS.messages))
    st.rerun()


def _date_label(ts: str) -> str:
    try:
        dt = datetime.datetime.strptime(ts, "%Y-%m-%dT%H:%M:%SZ")
        now = datetime.datetime.now(datetime.UTC)
        today = now.date()
        d = dt.date()
        if d == today:
            return "Today"
        if d == today - datetime.timedelta(days=1):
            return "Yesterday"
        return dt.strftime("%d %b %Y")
    except Exception:  # noqa: BLE001
        return "Earlier"


def _group_sessions(sessions: list) -> OrderedDict:
    groups: OrderedDict = OrderedDict()
    for s in sessions:
        label = _date_label(s.created_at)
        groups.setdefault(label, []).append(s)
    return groups


